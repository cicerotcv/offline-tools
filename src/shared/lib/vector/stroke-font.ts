/** Grid units from one character to the next (glyph 4 + spacing 2). */
const ADVANCE = 6;
const CAP_UNITS = 8;

export interface TextPathOptions {
  /** Left edge and baseline, in mm. */
  x: number;
  y: number;
  /** Height of a capital letter, in mm. */
  capHeight: number;
}

const round = (value: number) => Number(value.toFixed(3));

/** Width in mm of `text` set at `capHeight`. */
export function measureText(text: string, capHeight: number): number {
  const unit = capHeight / CAP_UNITS;
  return text.length === 0 ? 0 : ((text.length - 1) * ADVANCE + 4) * unit;
}

/**
 * Converts text to SVG path data (open polylines, to be stroked). Throws on
 * a character without a glyph rather than dropping it silently: a missing
 * character on an engraved share would make it unusable.
 */
export function textToPath(
  text: string,
  { x, y, capHeight }: TextPathOptions
): string {
  const unit = capHeight / CAP_UNITS;
  const top = y - CAP_UNITS * unit;
  return [...text]
    .map((char, i) => {
      const glyph = GLYPHS[char];
      if (!glyph) throw new Error(`No engraving glyph for "${char}"`);
      const left = x + i * ADVANCE * unit;
      return glyph
        .map((stroke) =>
          stroke
            .map(
              ([gx, gy], j) =>
                `${j === 0 ? 'M' : 'L'}${round(left + gx * unit)} ${round(top + gy * unit)}`
            )
            .join('')
        )
        .join('');
    })
    .join('');
}
