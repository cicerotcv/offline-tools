/*
 * Single-stroke engraving font for laser output. Glyphs are polylines on a
 * grid 4 units wide: capitals from y = 0 to the baseline at y = 8,
 * x-height at y = 3, descenders down to y = 10. A laser follows the strokes
 * as lines (crisp and fast) instead of filling outlines.
 *
 * Ambiguous base64url pairs are drawn apart on purpose: slashed zero vs O,
 * flagged and footed 1 vs tailed l vs serifed I, a short mid dash vs a
 * wide low underscore.
 */

